import { $, $$, clock, escapeHTML, loadJSON } from './common.js';

const box = $('#q');
const results = $('#results');
const statusLine = $('.results-status');
const filters = $('#filters');
let index = null;
let lower = [];

function say(text) { if (statusLine) statusLine.textContent = text; }

async function ensureIndex() {
  if (index) return index;
  say('Loading the transcripts…');
  index = await loadJSON('/data/search-index.json');
  lower = index.lines.map((line) => line[4].toLowerCase());
  if (filters) {
    filters.innerHTML = Object.entries(index.episodes).map(([id, ep]) => `<label><input type="checkbox" value="${escapeHTML(id)}" checked> ${escapeHTML(ep.short || ep.title)}</label>`).join('');
    filters.addEventListener('change', run);
  }
  say(`${index.lines.length.toLocaleString()} lines across ${Object.keys(index.episodes).length} episodes · built ${index.built.slice(0, 10)}.`);
  return index;
}

function highlight(text, terms) {
  let html = escapeHTML(text);
  for (const term of terms) html = html.replace(new RegExp(`(${term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')})`, 'ig'), '<mark>$1</mark>');
  return html;
}

async function run() {
  const q = box.value.trim();
  const url = new URL(location.href);
  if (q) url.searchParams.set('q', q); else url.searchParams.delete('q');
  history.replaceState(null, '', url);
  if (!q) { results.innerHTML = ''; if (index) say(`${index.lines.length.toLocaleString()} lines ready. Type a word, a name, a place.`); return; }
  await ensureIndex();
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
  const allowed = new Set($$('input:checked', filters).map((i) => i.value));
  const scored = [];
  for (let i = 0; i < lower.length; i += 1) {
    const line = index.lines[i];
    if (!allowed.has(line[0])) continue;
    const text = lower[i];
    let score = 0, ok = true;
    for (const term of terms) {
      const at = text.indexOf(term);
      if (at < 0) { ok = false; break; }
      score += 3 + (at === 0 || /\s/.test(text[at - 1] || ' ') ? 2 : 0);
    }
    if (!ok) continue;
    score -= Math.min(2, text.length / 400);
    scored.push([score, i]);
  }
  scored.sort((a, b) => b[0] - a[0] || a[1] - b[1]);
  const top = scored.slice(0, 150);
  results.innerHTML = top.map(([, i]) => {
    const [ep, start, , who, text] = index.lines[i];
    const episode = index.episodes[ep];
    return `<li><div class="meta"><a href="${escapeHTML(episode.url)}?t=${Math.floor(start)}">${escapeHTML(episode.short || episode.title)} · ${escapeHTML(clock(start))}</a><span>${escapeHTML(who || '')}</span></div><p>${highlight(text, terms)}</p></li>`;
  }).join('');
  say(scored.length ? `${scored.length.toLocaleString()} matching lines${scored.length > top.length ? ` · showing the first ${top.length}` : ''}. Each result opens the film at that moment.` : 'No line matches — try one word, or a first name.');
}

if (box) {
  let timer = 0;
  box.addEventListener('input', () => { clearTimeout(timer); timer = setTimeout(run, 160); });
  box.addEventListener('search', run);
  $('#search-form')?.addEventListener('submit', (event) => { event.preventDefault(); run(); });
  const initial = new URLSearchParams(location.search).get('q');
  if (initial) { box.value = initial; run(); } else ensureIndex().catch(() => say('The search index could not load; every transcript is still readable from the ledger links below.'));
}
